"""Build config/psc_categories.yaml from the official PSC manual workbook (acquisition.gov, April 2025).

Each 4-character PSC code maps to its "Level 1 Category" from the workbook (the government-wide
category management taxonomy). Ended codes are kept because older awards still use them.
Codes the workbook leaves without a category fall back to the majority category of mapped codes
sharing their 3-character, then 2-character prefix (lookup order: code, prefix3, prefix2).
Two retired IT families that FY2025 awards still use get an explicit override (LEGACY_PREFIXES).
"""
from collections import Counter
import os
import sys
from pathlib import Path

import pandas as pd
import yaml

SOURCE_URL = "https://www.acquisition.gov/sites/default/files/manual/PSC%20April%202025.xlsx"
xlsx = Path(sys.argv[1] if len(sys.argv) > 1 else Path(os.environ.get("DATA_DIR", "./data")) / "raw/psc/PSC_April_2025.xlsx")
# Retired groups with no Level 1 value whose workbook group names are IT, and whose replacements
# (D* "IT AND TELECOM" services, 7* IT products) are all Level 1 "IT".
LEGACY_PREFIXES = {
    "D3": {"category": "IT", "reason": "Group D3 'IT AND TELECOM' (ended 2020-10-29), replaced by DA-DK, all Level 1 IT"},
    "70": {"category": "IT", "reason": "Group 70 'INFORMATION TECHNOLOGY EQUIPMENT...' (ended 2020-10-29), replaced by 7A-7K, all Level 1 IT"},
}
df = pd.read_excel(xlsx, sheet_name=0, dtype=str)

# Category names keyed by Level 1 code; the workbook spells one name two ways ("Professional services").
names = (df.dropna(subset=["Level 1 Category Code", "Level 1 Category"])
           .groupby("Level 1 Category Code")["Level 1 Category"].agg(lambda s: s.mode()[0]).to_dict())
codes = df[df["PSC CODE"].str.len() == 4].dropna(subset=["Level 1 Category Code"])
mapping = {row["PSC CODE"]: names[row["Level 1 Category Code"]] for _, row in codes.sort_values("PSC CODE").iterrows()}


def majority_by_prefix(n):
    groups = {}
    for code, cat in mapping.items():
        groups.setdefault(code[:n], Counter())[cat] += 1
    return {k: c.most_common(1)[0][0] for k, c in sorted(groups.items())}


prefix3 = majority_by_prefix(3)
prefix2 = {**majority_by_prefix(2), **{k: v["category"] for k, v in LEGACY_PREFIXES.items()}}
all_codes = set(df.loc[df["PSC CODE"].str.len() == 4, "PSC CODE"])
unmapped = sorted(c for c in all_codes - set(mapping) if c[:3] not in prefix3 and c[:2] not in prefix2)

# Definitions: the Level 2 category names under each Level 1 category, straight from the workbook.
level2 = (df.dropna(subset=["Level 1 Category Code", "Level 2 Category"])
            .groupby("Level 1 Category Code")["Level 2 Category"].agg(lambda s: sorted(set(s))).to_dict())
definitions = {names[c]: "Includes: " + "; ".join(v) for c, v in sorted(level2.items())}
# Categories without Level 2 entries (R&D) use the names of the active 2-character PSC groups they contain.
groups = df[(df["PSC CODE"].str.len() == 2) & df["END DATE"].isna()].set_index("PSC CODE")["PRODUCT AND SERVICE CODE NAME"]
for cat in sorted(set(mapping.values()) - set(definitions)):
    members = sorted({code[:2] for code, c in mapping.items() if c == cat} & set(groups.index))
    definitions[cat] = "Includes: " + "; ".join(groups[g].strip().title() for g in members)

doc = {
    "source": {"name": "PSC Manual April 2025 (FY2025), Level 1 Category column", "url": SOURCE_URL},
    "categories": sorted(set(mapping.values())),
    "category_definitions": definitions,
    "unmapped_psc_codes": unmapped,   # 4-char codes with no category even after prefix fallback
    "psc_to_category": mapping,
    "prefix3_to_category": prefix3,
    "prefix2_to_category": prefix2,
    "legacy_prefix_overrides": LEGACY_PREFIXES,
}
out = Path("config/psc_categories.yaml")
out.write_text("# Generated by scripts/data/build_psc_categories.py; do not edit by hand.\n"
               + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))
print(f"{len(doc['categories'])} categories, {len(mapping)} codes mapped directly, "
      f"{len(all_codes - set(mapping)) - len(unmapped)} via prefix, {len(unmapped)} unmapped -> {out}")
